// 生成简单的 PNG 图标
// 运行: node generate-icon.js

const fs = require('fs');
const path = require('path');

// 创建一个 16x16 的简单 PNG 文件
function createPNG() {
  // 最简单的 PNG：1x1 像素的紫色方块
  // 这是一个预编码的 PNG 文件数据
  const pngData = Buffer.from([
    // PNG 签名
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
    // IHDR 块
    0x00, 0x00, 0x00, 0x0D, // 长度
    0x49, 0x48, 0x44, 0x52, // 类型: IHDR
    0x00, 0x00, 0x00, 0x10, // 宽度: 16
    0x00, 0x00, 0x00, 0x10, // 高度: 16
    0x08, // 位深度: 8
    0x02, // 颜色类型: RGB
    0x00, // 压缩方法
    0x00, // 滤波方法
    0x00, // 交错方法
    // CRC
    0x94, 0x95, 0x6A, 0xFC,
    // IDAT 块 (压缩的图像数据)
    0x00, 0x00, 0x00, 0x34, // 长度
    0x49, 0x44, 0x41, 0x54, // 类型: IDAT
    // 压缩数据 (使用 deflate)
    0x78, 0x9C, 0x62, 0x60, 0x60, 0x60, 0x60, 0x60,
    0x66, 0x60, 0x60, 0x66, 0x66, 0x66, 0x66, 0x66,
    0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66,
    0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66,
    0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66,
    0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x66,
    0x66, 0x66, 0x66, 0x66, 0x66, 0x66, 0x01,
    // CRC
    0x00, 0x00, 0x00, 0x00,
    // IEND 块
    0x00, 0x00, 0x00, 0x00, // 长度: 0
    0x49, 0x45, 0x4E, 0x44, // 类型: IEND
    0xAE, 0x42, 0x60, 0x82  // CRC
  ]);

  return pngData;
}

// 保存 PNG 文件
const iconPath = path.join(__dirname, 'icon.png');
const pngData = createPNG();
fs.writeFileSync(iconPath, pngData);
console.log('✅ 已创建 icon.png:', iconPath);
console.log('文件大小:', pngData.length, '字节');

// 验证文件
if (fs.existsSync(iconPath)) {
  console.log('✅ 文件已存在，可以使用');
} else {
  console.log('❌ 文件创建失败');
}
